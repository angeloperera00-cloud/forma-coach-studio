/**
 * Writes supabase/seed.sql with the starter exercise & food libraries.
 * Usage: npm run db:seed-sql
 *
 * Only libraries are seeded — never demo clients — so real coaching data stays separate.
 * Food values are flagged source = 'demo' (indicative) until the coach verifies them.
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { buildExerciseLibrary, buildFoodLibrary } from "../src/lib/data/seed/library";

const q = (v: string | null | undefined) => (v === null || v === undefined ? "null" : `'${v.replace(/'/g, "''")}'`);
const n = (v: number | null | undefined) => (v === null || v === undefined ? "null" : String(v));
const arr = (list: string[]) => (list.length ? `array[${list.map(q).join(", ")}]::text[]` : "'{}'::text[]");

const now = new Date().toISOString();
const exercises = buildExerciseLibrary(now);
const foods = buildFoodLibrary(now);

const lines: string[] = [
  "-- Forma starter libraries (generated by scripts/generate-seed-sql.ts — do not edit by hand)",
  "-- Safe to run more than once.",
  "begin;",
  "",
  "-- Exercises (photos: free-exercise-db, public domain)",
];
for (const e of exercises) {
  lines.push(
    `insert into public.exercises (id, name, primary_muscles, secondary_muscles, equipment, difficulty, instructions, image_urls, is_custom) values (${q(e.id)}, ${q(e.name)}, ${arr(e.primaryMuscles)}, ${arr(e.secondaryMuscles)}, ${q(e.equipment)}, ${q(e.difficulty)}, ${arr(e.instructions)}, ${arr(e.imageUrls)}, false) on conflict (id) do nothing;`,
  );
}
lines.push("", "-- Foods (indicative values per 100 g/ml — verify before use)");
for (const f of foods) {
  lines.push(
    `insert into public.foods (id, name, category, kind, image_url, unit, serving_size, serving_label, kcal_100, protein_100, carbs_100, fat_100, servings, source, source_ref, is_custom) values (${q(f.id)}, ${q(f.name)}, ${q(f.category)}, ${q(f.kind)}, ${q(f.imageUrl)}, ${q(f.unit)}, ${n(f.servingSize)}, ${q(f.servingLabel)}, ${n(f.per100.kcal)}, ${n(f.per100.protein)}, ${n(f.per100.carbs)}, ${n(f.per100.fat)}, ${n(f.servings)}, ${q(f.source)}, ${q(f.sourceRef)}, false) on conflict (id) do nothing;`,
  );
}
lines.push("", "-- Recipe ingredients");
for (const f of foods.filter((x) => x.kind === "recipe")) {
  lines.push(`delete from public.recipe_ingredients where recipe_id = ${q(f.id)};`);
  f.ingredients.forEach((ing, i) => {
    lines.push(`insert into public.recipe_ingredients (recipe_id, food_id, amount, position) values (${q(f.id)}, ${q(ing.foodId)}, ${n(ing.amount)}, ${i});`);
  });
}
lines.push("", "commit;", "");

const out = path.join(process.cwd(), "supabase", "seed.sql");
writeFileSync(out, lines.join("\n"));
console.log(`Wrote ${exercises.length} exercises and ${foods.length} foods to ${path.relative(process.cwd(), out)}`);
